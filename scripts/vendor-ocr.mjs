// Downloads the pinned report-reading assets (public/ocr-assets.mjs) into public/vendor/ocr/<OCR_ID>/ (gitignored).
// Every tarball and every copied file is checked against its sha256; nothing is written unless all match. Tarballs
// are cached (~/.cache/apnihealth-ocr or $APNI_OCR_CACHE), so later runs need no network. build.py runs this.
// Run: node scripts/vendor-ocr.mjs [--check] [--offline] [--out DIR]
//   --check    only verify the installed files (no network, exit 1 if anything is missing or different)
//   --offline  use cached tarballs only
import {createHash} from 'node:crypto';
import {gunzipSync} from 'node:zlib';
import {mkdirSync,readFileSync,writeFileSync,existsSync,renameSync,rmSync,mkdtempSync} from 'node:fs';
import {join,dirname,resolve} from 'node:path';
import {homedir} from 'node:os';
import {fileURLToPath} from 'node:url';
import {OCR_ID,PACKAGES,LANG_NOTICE} from '../public/ocr-assets.mjs';

const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const sha=b=>createHash('sha256').update(b).digest('hex');

// The files of a .tgz as Map(path → Buffer): ustar headers (with the prefix field) and pax/GNU long names.
export function untar(tgz){
 const t=gunzipSync(tgz),out=new Map();let pos=0,longName=null;
 const str=(o,n)=>t.subarray(o,o+n).toString('utf8').replace(/\0.*$/s,'');
 while(pos+512<=t.length){
  if(t.subarray(pos,pos+512).every(b=>b===0))break;
  const size=parseInt(str(pos+124,12).trim()||'0',8),type=str(pos+156,1)||'0';
  let name=str(pos,100);const prefix=str(pos+345,155);if(prefix)name=prefix+'/'+name;
  const data=t.subarray(pos+512,pos+512+size);pos+=512+Math.ceil(size/512)*512;
  if(type==='L'){longName=data.toString('utf8').replace(/\0.*$/s,'');continue}
  if(type==='x'){const m=/\d+ path=([^\n]*)\n/.exec(data.toString('utf8'));if(m)longName=m[1];continue}
  if(longName){name=longName;longName=null}
  if(type==='0'||type==='\0')out.set(name,Buffer.from(data));
 }
 return out;
}

export function check(dir,packages=PACKAGES){
 const bad=[];
 for(const p of packages)for(const f of p.files){
  const file=join(dir,f.to);
  if(!existsSync(file))bad.push(f.to+': missing');else if(sha(readFileSync(file))!==f.sha256)bad.push(f.to+': sha256 differs');
 }
 return bad;
}

async function tarball(p,{cache,offline}){
 const file=join(cache,`${p.name.replace('/','__')}-${p.version}.tgz`);
 if(existsSync(file)){const b=readFileSync(file);if(sha(b)===p.sha256)return b;rmSync(file)}
 if(offline)throw Error(`${p.name}@${p.version}: not in the cache (${cache}) and --offline is set`);
 const r=await fetch(p.tarball,{redirect:'follow'});
 if(!r.ok)throw Error(`${p.name}@${p.version}: download failed (HTTP ${r.status})`);
 const b=Buffer.from(await r.arrayBuffer());
 if(sha(b)!==p.sha256)throw Error(`${p.name}@${p.version}: tarball sha256 differs from public/ocr-assets.mjs; refusing to use it`);
 mkdirSync(cache,{recursive:true});writeFileSync(file+'.tmp',b);renameSync(file+'.tmp',file);
 return b;
}

export async function vendor({out=join(root,'public/vendor/ocr'),cache=process.env.APNI_OCR_CACHE||join(homedir(),'.cache/apnihealth-ocr'),offline=false,log=console.log,packages=PACKAGES,id=OCR_ID}={}){
 const dir=join(out,id);
 if(!check(dir,packages).length){log(`OCR assets ok: ${dir}`);return dir}
 mkdirSync(out,{recursive:true});
 const tmp=mkdtempSync(join(out,'.tmp-'));
 try{
  for(const p of packages){
   const files=untar(await tarball(p,{cache,offline}));
   for(const f of p.files){
    const b=files.get(f.from);
    if(!b)throw Error(`${p.name}@${p.version}: ${f.from} is not in the tarball`);
    if(sha(b)!==f.sha256)throw Error(`${p.name}@${p.version}: ${f.from} sha256 differs; refusing to use it`);
    mkdirSync(dirname(join(tmp,f.to)),{recursive:true});writeFileSync(join(tmp,f.to),b);
   }
   for(const [from,to] of p.licenses){
    const b=files.get(from);if(!b)throw Error(`${p.name}@${p.version}: licence ${from} is not in the tarball`);
    mkdirSync(dirname(join(tmp,to)),{recursive:true});writeFileSync(join(tmp,to),b);
   }
  }
  mkdirSync(join(tmp,'lang'),{recursive:true});writeFileSync(join(tmp,'lang/NOTICE'),LANG_NOTICE);
  writeFileSync(join(tmp,'README'),`Generated by scripts/vendor-ocr.mjs from public/ocr-assets.mjs. Do not edit or commit.\n${packages.map(p=>`${p.name} ${p.version} (${p.license})`).join('\n')}\n`);
  const bad=check(tmp,packages);if(bad.length)throw Error(bad.join('; '));
  rmSync(dir,{recursive:true,force:true});renameSync(tmp,dir);
 }finally{rmSync(tmp,{recursive:true,force:true})}
 log(`OCR assets installed: ${dir}`);
 return dir;
}

if(process.argv[1]&&resolve(process.argv[1])===fileURLToPath(import.meta.url)){
 const a=process.argv.slice(2),opt=n=>{const i=a.indexOf(n);return i>=0?a[i+1]:undefined};
 const out=opt('--out')?resolve(opt('--out')):undefined;
 try{
  if(a.includes('--check')){
   const bad=check(join(out||join(root,'public/vendor/ocr'),OCR_ID));
   if(bad.length){console.error('OCR assets not installed or changed:\n  '+bad.join('\n  ')+'\nRun: node scripts/vendor-ocr.mjs');process.exit(1)}
   console.log('OCR assets ok');
  }else await vendor({out,offline:a.includes('--offline')});
 }catch(e){console.error('vendor-ocr: '+e.message);process.exit(1)}
}
